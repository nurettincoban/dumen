// ActivityDays is how many of the most recent days ACTIVITY.md covers.
const ActivityDays = 14

const generated = "<!-- Generated by dumen from the records on this branch. Do not edit: changes are overwritten. -->\n"

// cell makes text safe inside a Markdown table cell or list item.
func cell(s string, max int) string {
	s = Label(s, max)
	s = strings.NewReplacer("|", "\\|", "<", "&lt;", ">", "&gt;", "`", "'", "[", "(", "]", ")").Replace(s)
	if s == "" {
		return "-"
	}
	return s
}

func day(ts string) string {
	if len(ts) >= 10 {
		return ts[:10]
	}
	return ts
}

// Decisions renders DECISIONS.md. The output depends only on the records, never on the
// clock, so regenerating from the same state gives the same bytes.
func Decisions(root string) ([]byte, error) {
	decs, err := store.ListDecisions(root)
	if err != nil {
		return nil, err
	}
	dirs, err := store.ListDirectives(root)
	if err != nil {
		return nil, err
	}
	refs, err := store.ListRefs(root)
	if err != nil {
		return nil, err
	}
	derived := policy.Derive(decs)

	var b strings.Builder
	b.WriteString("# Decisions\n\n" + generated)

	b.WriteString("\n## Directives\n\n")
	var active []model.Directive
	for _, d := range dirs {
		if d.Status == model.DirectiveActive {
			active = append(active, d)
		}
	}
	if len(active) == 0 {
		b.WriteString("No published directives.\n")
	} else {
		b.WriteString("A directive is in force between its start and expiry times (UTC).\n\n")
		b.WriteString("| ID | Kind | Scope | Starts | Expires | Published by | Text |\n|---|---|---|---|---|---|---|\n")
		for _, d := range active {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", d.ID, d.Kind, cell(d.Scope.String(), 80),
				d.Starts, d.Expires, cell(d.PublishedBy, 60), cell(d.Text, 300))
		}
	}

	b.WriteString("\n## Approved decisions\n")
	byArea := map[string][]model.Decision{}
	var drafts, superseded []model.Decision
	for _, d := range decs {
		switch d.Status {
		case model.StatusApproved:
			if len(derived.SupersededBy[d.ID]) == 1 {
				superseded = append(superseded, d)
				continue
			}
			byArea[d.Area] = append(byArea[d.Area], d)
		case model.StatusProposed:
			drafts = append(drafts, d)
		}
	}
	areas := model.SortedKeys(byArea)
	sort.SliceStable(areas, func(i, j int) bool { return areas[i] != "" && areas[j] == "" }) // no area last
	if len(areas) == 0 {
		b.WriteString("\nNo approved decisions.\n")
	}
	for _, a := range areas {
		name := a
		if name == "" {
			name = "(no area)"
		}
		fmt.Fprintf(&b, "\n### %s\n\n", cell(name, 60))
		for _, d := range byArea[a] {
			fmt.Fprintf(&b, "- **%s** %s", d.ID, cell(d.Title, MaxLabel))
			if derived.Contested[d.ID] {
				fmt.Fprintf(&b, " (CONTESTED: superseded by %s)", strings.Join(derived.SupersededBy[d.ID], " and "))
			}
			if len(d.Supersedes) > 0 {
				fmt.Fprintf(&b, " (supersedes %s)", strings.Join(d.Supersedes, ", "))
			}
			if len(d.Paths) > 0 {
				fmt.Fprintf(&b, "; paths: %s", cell(strings.Join(d.Paths, ", "), 200))
			}
			if len(d.Sources) > 0 {
				fmt.Fprintf(&b, "; sources: %s", strings.Join(d.Sources, ", "))
			}
			fmt.Fprintf(&b, "; approved by %s; %s\n", cell(d.ApprovedBy, 60), day(d.Created))
		}
	}
	if len(superseded) > 0 {
		b.WriteString("\n## Superseded\n\n")
		for _, d := range superseded {
			fmt.Fprintf(&b, "- %s %s; superseded by %s\n", d.ID, cell(d.Title, MaxLabel), derived.SupersededBy[d.ID][0])
		}
	}

	fmt.Fprintf(&b, "\n## Drafts (%d)\n\n", len(drafts))
	if len(drafts) == 0 {
		b.WriteString("No drafts awaiting review.\n")
	}
	for _, d := range drafts {
		fmt.Fprintf(&b, "- %s %s; by %s (%s); %s\n", d.ID, cell(d.Title, MaxLabel), cell(d.Author, 60), d.AuthorKind, day(d.Created))
	}

	b.WriteString("\n## Sources of truth\n\n")
	if len(refs) == 0 {
		b.WriteString("No links recorded.\n")
	} else {
		b.WriteString("Links and one-line labels only. The linked document is the source of truth.\n\n")
		b.WriteString("| ID | Kind | Title | Link | Governs | Area | Last checked |\n|---|---|---|---|---|---|---|\n")
		for _, r := range refs {
			title := cell(r.Title, MaxLabel)
			if r.Status == model.RefUnverified {
				title = "(unverified, added by an agent) " + title
			}
			fmt.Fprintf(&b, "| %s | %s | %s | <%s> | %s | %s | %s |\n", r.ID, r.Kind, title,
				strings.NewReplacer(">", "%3E", "<", "%3C", " ", "%20", "|", "%7C").Replace(Label(r.URL, 500)),
				cell(r.Governs, MaxLabel), cell(r.Area, 40), checked(r))
		}
	}
	return []byte(b.String()), nil
}

// Activity renders ACTIVITY.md: a per-day summary of agent sessions for the most recent days.
func Activity(root string) ([]byte, error) {
	days, err := store.ListDays(root)
	if err != nil {
		return nil, err
	}
	if len(days) > ActivityDays {
		days = days[len(days)-ActivityDays:]
	}
	var b strings.Builder
	b.WriteString("# Activity\n\n" + generated)
	if len(days) == 0 {
		b.WriteString("\nNo activity recorded yet.\n")
	}
	for i := len(days) - 1; i >= 0; i-- {
		evs, err := store.ReadEvents(root, days[i])
		if err != nil {
			return nil, err
		}
		sum := activity.Summarize(evs)
		fmt.Fprintf(&b, "\n## %s\n\n", days[i])
		fmt.Fprintf(&b, "%d sessions: %d started, %d finished, %d blocked events, %d times asking a human, %d not monitored.\n",
			len(sum.Sessions), sum.Counts[model.EventStarted], sum.Counts[model.EventFinished],
			sum.Counts[model.EventBlocked], sum.Counts[model.EventAskingHuman], sum.Counts[model.EventPrivate])
		if len(sum.Sessions) > 0 {
			b.WriteString("\n| Person | Repo | Session | First | Last | State | Last note |\n|---|---|---|---|---|---|---|\n")
			for _, s := range sum.Sessions {
				fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", cell(s.Person, 60), cell(s.Repo, 40), cell(s.Session, 16),
					clock(s.First), clock(s.Last), s.State, cell(s.LastText, 160))
			}
		}
		var attention []model.Event
		for _, e := range evs {
			if e.Kind == model.EventBlocked || e.Kind == model.EventAskingHuman {
				attention = append(attention, e)
			}
		}
		if len(attention) > 0 {
			b.WriteString("\nBlocked or waiting on a person:\n\n")
			for _, e := range attention {
				ids := ""
				if len(e.IDs) > 0 {
					ids = " (" + strings.Join(e.IDs, ", ") + ")"
				}
				fmt.Fprintf(&b, "- %s %s %s: %s%s\n", clock(e.TS), cell(e.Person, 60), e.Kind, cell(e.Text, 200), ids)
			}
		}
		if len(sum.Violations) > 0 {
			b.WriteString("\nChanges left under a deny directive:\n\n")
			for _, e := range sum.Violations {
				fmt.Fprintf(&b, "- %s %s: %s (%s)\n", clock(e.TS), cell(e.Person, 60), cell(e.Text, 200), strings.Join(e.IDs, ", "))
			}
		}
	}
	return []byte(b.String()), nil
}

func clock(ts string) string {
	if len(ts) >= 16 {
		return ts[11:16]
	}
	return ts
}

// Regenerate rewrites DECISIONS.md and ACTIVITY.md in root.
func Regenerate(root string) error {
	d, err := Decisions(root)
	if err != nil {
		return err
	}
	a, err := Activity(root)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, store.DecisionsMD), d, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, store.ActivityMD), a, 0o644)
}

func checked(r model.Ref) string {
	if r.Status == model.RefUnverified {
		return "not yet, added by an agent"
	}
	return day(r.CheckedAt)
}
